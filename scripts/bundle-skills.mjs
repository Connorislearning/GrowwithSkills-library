// Packs every skills/<category>/<name>/SKILL.md (and README.md) into src/skills.generated.ts.
// Wrangler runs this before every dev and deploy (see "build" in wrangler.jsonc).
// A skill is served only when its frontmatter metadata has `public: true`.
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const skillsDir = join(root, "skills");

// Simple line-by-line `key: value` reader. Indented keys (inside `metadata:`) are read the same way.
function frontmatter(text) {
	const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
	const meta = {};
	if (!m) return meta;
	for (const line of m[1].split(/\r?\n/)) {
		const i = line.indexOf(":");
		if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, "");
	}
	return meta;
}

const isDir = (p) => existsSync(p) && statSync(p).isDirectory();
const skills = [];
for (const category of readdirSync(skillsDir).sort()) {
	const catDir = join(skillsDir, category);
	if (!isDir(catDir)) continue;
	for (const folder of readdirSync(catDir).sort()) {
		const dir = join(catDir, folder);
		const file = join(dir, "SKILL.md");
		if (!isDir(dir) || !existsSync(file)) continue;
		const content = readFileSync(file, "utf8");
		const meta = frontmatter(content);
		if (!meta.description) {
			console.error(`skills/${category}/${folder}/SKILL.md is missing a description`);
			process.exit(1);
		}
		if (meta.public !== "true") continue;
		const readmePath = join(dir, "README.md");
		const readme = existsSync(readmePath) ? readFileSync(readmePath, "utf8") : "";
		skills.push({ name: meta.name || folder, category, description: meta.description, content, readme });
	}
}

writeFileSync(
	join(root, "src", "skills.generated.ts"),
	`// Generated by scripts/bundle-skills.mjs. Do not edit by hand.\nexport const SKILLS: { name: string; category: string; description: string; content: string; readme: string }[] = ${JSON.stringify(skills, null, "\t")};\n`,
);
console.log(`Bundled ${skills.length} public skill(s)`);
